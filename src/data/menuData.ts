// Helper to format currency in Brazilian Real
export const formatBRL = (value: number | undefined): string => {
  if (value === undefined || value === null || isNaN(value)) return 'R$ 0,00';
  return new Intl.NumberFormat('pt-BR', {
    style: 'currency',
    currency: 'BRL',
  }).format(value);
};

// Helper to get product price for a specific size
export const getFlavorPriceForSize = (flavor: Product, size: PizzaSize = 'pizza'): number => {
  if (flavor.pricesBySize && flavor.pricesBySize[size] !== undefined) {
    return flavor.pricesBySize[size]!;
  }
  return flavor.price;
};

// Returns highest priced flavor among selected flavors for a given size
export const getHighestPricedFlavor = (
  flavors: Product[],
  size: PizzaSize = 'pizza'
): { flavor: Product; price: number } | null => {
  if (!flavors || flavors.length === 0) return null;
  let highest = flavors[0];
  let maxPrice = getFlavorPriceForSize(highest, size);
  for (let i = 1; i < flavors.length; i++) {
    const p = getFlavorPriceForSize(flavors[i], size);
    if (p > maxPrice) {
      maxPrice = p;
      highest = flavors[i];
    }
  }
  return { flavor: highest, price: maxPrice };
};

// Calculates multi-flavor pizza price: strictly the HIGHEST price among all chosen flavors
// (No average, no sum, no division — always the highest flavor price)
export const calculateMultiFlavorPizzaPrice = (
  flavors: Product[],
  size: PizzaSize = 'pizza'
): number => {
  if (!flavors || flavors.length === 0) return 0;
  const prices = flavors.map((f) => getFlavorPriceForSize(f, size));
  return Math.max(...prices);
};

// Calculates pizza price (supports 1, 2, or 3 flavors using max flavor rule)
export const calculatePizzaPrice = (
  primary: Product,
  secondaryOrFlavors?: Product | Product[],
  size: PizzaSize = 'pizza'
): number => {
  if (Array.isArray(secondaryOrFlavors)) {
    const list = [primary, ...secondaryOrFlavors.filter((p) => p.id !== primary.id)];
    return calculateMultiFlavorPizzaPrice(list, size);
  }
  if (secondaryOrFlavors) {
    return calculateMultiFlavorPizzaPrice([primary, secondaryOrFlavors], size);
  }
  return getFlavorPriceForSize(primary, size);
};
